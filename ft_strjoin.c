#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	char	*result;
	size_t	i;
	size_t	j;

	if (!s1 || !s2)
		return (NULL);
	
	i = 0;
	j = 0;
	while (s1[i])
		i++;
	while (s2[j])
		j++;

	result = malloc(sizeof(char) * (i + j + 1));
	if (!result)
		return (NULL);

	i = 0;
	while (s1[i])
	{
		result[i] = s1[i];
		i++;
	}
	j = 0;
	while (s2[j])
	{
		result[i + j] = s2[j];
		j++;
	}
	result[i + j] = '\0';

	return (result);
}
